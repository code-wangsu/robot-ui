export * from '@robot-ui/utils'

export interface RobotUIOptions {
  prefix?: string
}

const $rb = {
  ...utils,
  version: utils.version,
}

export function registerComponents(app: App, prefix = 'Rb') {
  registerAll(app, prefix)
}

export function install(app: App, options: RobotUIOptions = {}) {
  registerComponents(app, options.prefix)
  app.config.globalProperties.$rb = $rb
}

